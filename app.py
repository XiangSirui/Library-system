def _json_body():
    data = request.get_json(force=True, silent=True)
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise BadRequest('请求内容必须为 JSON 对象')
    text_fields = ('bookId', 'name', 'phone', 'card', 'date', 'timeSlot',
                   'purpose', 'volunteerNote', 'volunteerImage', 'content',
                   'username', 'password', 'title', 'author', 'category',
                   'isbn', 'coverIsbn', 'reason')
    for key in text_fields:
        if key in data and data[key] is not None and not isinstance(data[key], str):
            raise BadRequest(f'{key} 必须为文本')
    for key in ('duration', 'attendees', 'rating', 'copies'):
        if key in data and data[key] is not None:
            try:
                if isinstance(data[key], bool):
                    raise ValueError()
                data[key] = int(str(data[key]).strip())
            except (ValueError, TypeError):
                raise BadRequest(f'{key} 必须为整数')
    return data


