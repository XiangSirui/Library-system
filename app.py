def _save_volunteer_image(file_storage):
    if not file_storage or not file_storage.filename:
        return None, '请上传社区花园志愿服务照片'
    filename = secure_filename(file_storage.filename)
    ext = os.path.splitext(filename)[1].lower()
    if ext not in ALLOWED_IMAGE_EXT:
        return None, '图片格式仅支持 JPG / PNG / WEBP / GIF'
    try:
        with Image.open(file_storage.stream) as image:
            expected = {'.jpg': 'JPEG', '.jpeg': 'JPEG', '.png': 'PNG',
                        '.webp': 'WEBP', '.gif': 'GIF'}
            if image.format != expected[ext] or image.width * image.height > 25000000:
                return None, '照片格式不匹配或尺寸过大，请重新选择'
            image.verify()
    except (UnidentifiedImageError, OSError, ValueError, Image.DecompressionBombError):
        return None, '照片文件无效，请重新选择'
    finally:
        file_storage.stream.seek(0)
    new_name = f'{uuid.uuid4().hex}{ext}'
    path = os.path.join(UPLOAD_DIR, new_name)
    file_storage.save(path)
    return f'/static/uploads/volunteer/{new_name}', None


def _remove_uploaded_image(image_url):
    # Only URLs generated by _save_volunteer_image reach this helper.
    path = os.path.join(UPLOAD_DIR, os.path.basename(image_url))
    try:
        os.remove(path)
    except FileNotFoundError:
        pass


def admin_required(f):
    @wraps(f)
    def decorated(*args, **kwargs):
        if not session.get('admin_id'):
            if request.path.startswith('/api/'):
                return jsonify({'error': '请先登录管理员账号'}), 401
            return redirect(url_for('admin_login_page'))
        return f(*args, **kwargs)
    return decorated


